function dependenciesFor(relativeFile) {
  const source = readFileSync(resolve(root, relativeFile), 'utf8');
  return [...new Set(Array.from(
    source.matchAll(/\bruntime\.([A-Za-z_$][\w$]*)/g),
    (match) => match[1],
  ))].sort();
}

const entries = Object.entries(domainFiles).map(([domain, file]) => (
  `  ${JSON.stringify(domain)}: Object.freeze(${JSON.stringify(dependenciesFor(file))}),`
));
const output = [
  '// Generated by scripts/generate-domain-dependencies.mjs. Do not edit by hand.',
  'export const domainDependencies = Object.freeze({',
  ...entries,
  '});',
  '',
].join('\n');

if (process.argv.includes('--check')) {
  const current = readFileSync(outputFile, 'utf8');
  if (current !== output) {
    console.error('Domain dependency manifest is stale. Run npm run generate:domain-deps.');
    process.exitCode = 1;
  }
} else {
  writeFileSync(outputFile, output, 'utf8');
}
